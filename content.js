export function allSelectableAbilities(origins = []) {
  const originAbilities = origins.map((origin) => {
    const [summary = `Habilidade concedida pela origem ${origin.name}.`, cost = "Passivo"] = ORIGIN_POWER_DETAILS[origin.power] ?? [];
    return ability({
      name: origin.power,
      category: "Origens",
      group: origin.name,
      summary,
      cost,
      requirement: `Origem ${origin.name}`,
      source: origin.source,
    });
  });
  return [...CLASS_POWERS, ...TRAIL_ABILITIES, ...PARANORMAL_POWERS, ...originAbilities];
}
