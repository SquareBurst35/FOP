const slug = (value) =>
  String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const ability = ({ name, category, group, summary, cost = "Passivo", requirement = "Nenhum", unlockNex = 0, source = "Livro base" }) => ({
  id: slug(`${category}-${group}-${name}`),
  name,
  category,
  group,
  summary,
  cost,
  requirement,
  unlockNex,
  source,
});

